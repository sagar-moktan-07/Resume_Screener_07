-- =====================================================================
-- Resume Screener schema (PostgreSQL)
-- Run as the owner role:  psql -h localhost -U resume_app -d resumedb -f db/schema.sql
-- Requires the roles resume_app and fastapi_svc to exist already.
-- =====================================================================
BEGIN;

-- ---------------------------------------------------------------------
-- 1. credentials_all : login accounts (used by Spring Boot only)
-- ---------------------------------------------------------------------
CREATE TABLE credentials_all (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username       VARCHAR(50)  NOT NULL,
    email          VARCHAR(255) NOT NULL,
    full_name      VARCHAR(100),
    password_hash  VARCHAR(255) NOT NULL,             -- BCrypt hash, never the real password
    role           VARCHAR(20)  NOT NULL,
    enabled        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMP    NOT NULL DEFAULT now(),

    CONSTRAINT uk_credentials_username       UNIQUE (username),
    CONSTRAINT uk_credentials_email          UNIQUE (email),
    CONSTRAINT ck_credentials_role           CHECK (role IN ('USER', 'ADMIN')),
    CONSTRAINT ck_credentials_username_lower CHECK (username = lower(username)),
    CONSTRAINT ck_credentials_email_lower    CHECK (email = lower(email))
);

-- ---------------------------------------------------------------------
-- 2. candidates : one row per uploaded / emailed resume
-- ---------------------------------------------------------------------
CREATE TABLE candidates (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_name          VARCHAR(255) NOT NULL,
    full_name          VARCHAR(255),
    email              VARCHAR(255),
    phone              VARCHAR(255),
    qualifications     TEXT,
    skills             TEXT,
    experience         TEXT,
    raw_text           TEXT,                          -- full PDF text, for the model
    uploaded_at        TIMESTAMP    NOT NULL DEFAULT now(),

    -- Where the resume came from (columns reserved for the Gmail importer)
    source             VARCHAR(20)  NOT NULL DEFAULT 'upload',
    source_message_id  VARCHAR(255),
    sender_email       VARCHAR(255),
    received_at        TIMESTAMP,

    CONSTRAINT ck_candidates_source CHECK (source IN ('upload', 'gmail'))
);

CREATE INDEX idx_candidates_email ON candidates (lower(email));

-- The same email attachment can never be imported twice
CREATE UNIQUE INDEX uq_candidates_gmail_source
    ON candidates (source_message_id, file_name)
    WHERE source_message_id IS NOT NULL;

-- ---------------------------------------------------------------------
-- 3. candidate_profiles : structured data extracted from each resume
--    (written by FastAPI; one row per candidate)
-- ---------------------------------------------------------------------
CREATE TABLE candidate_profiles (
    candidate_id            BIGINT PRIMARY KEY
                            REFERENCES candidates(id) ON DELETE CASCADE,
    highest_degree          VARCHAR(20),
    field_of_study          VARCHAR(255),
    certifications          JSONB        NOT NULL DEFAULT '[]',   -- ["AWS Cloud Practitioner", ...]
    skills                  JSONB        NOT NULL DEFAULT '[]',   -- normalized skill names
    jobs                    JSONB        NOT NULL DEFAULT '[]',   -- [{title, company, start, end, tech}, ...]
    total_experience_years  NUMERIC(4,1),                         -- computed in code from job dates
    extractor_model         VARCHAR(100),
    extracted_at            TIMESTAMP    NOT NULL DEFAULT now(),

    CONSTRAINT ck_profiles_degree
        CHECK (highest_degree IN ('none', 'diploma', 'bachelor', 'master', 'phd'))
);

-- ---------------------------------------------------------------------
-- 4. vacancies : job templates (created in the Spring UI later)
-- ---------------------------------------------------------------------
CREATE TABLE vacancies (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title                 VARCHAR(200) NOT NULL,
    description           TEXT         NOT NULL DEFAULT '',
    required_skills       JSONB        NOT NULL DEFAULT '[]',
    nice_to_have_skills   JSONB        NOT NULL DEFAULT '[]',
    qualifications        JSONB        NOT NULL DEFAULT '[]',     -- any-of keywords
    min_degree_level      VARCHAR(20),
    min_experience_years  NUMERIC(4,1) NOT NULL DEFAULT 0,
    weights               JSONB        NOT NULL
        DEFAULT '{"skills": 40, "experience": 30, "education": 15, "qualifications": 15}',
    is_open               BOOLEAN      NOT NULL DEFAULT TRUE,
    created_by            BIGINT REFERENCES credentials_all(id) ON DELETE SET NULL,
    created_at            TIMESTAMP    NOT NULL DEFAULT now(),

    CONSTRAINT ck_vacancies_degree
        CHECK (min_degree_level IN ('none', 'diploma', 'bachelor', 'master', 'phd'))
);

-- ---------------------------------------------------------------------
-- 5. shortlist_runs : one row per "find top N" job (id = FastAPI job id)
-- ---------------------------------------------------------------------
CREATE TABLE shortlist_runs (
    id                VARCHAR(32) PRIMARY KEY,
    vacancy_id        BIGINT REFERENCES vacancies(id) ON DELETE SET NULL,
    vacancy_snapshot  JSONB       NOT NULL,          -- the exact vacancy used for this run
    top_n             INT         NOT NULL DEFAULT 7,
    model             VARCHAR(100) NOT NULL,
    status            VARCHAR(10) NOT NULL DEFAULT 'queued',
    error             TEXT,
    started_at        TIMESTAMP   NOT NULL DEFAULT now(),
    finished_at       TIMESTAMP,

    CONSTRAINT ck_runs_id     CHECK (id ~ '^[a-f0-9]{32}$'),
    CONSTRAINT ck_runs_status CHECK (status IN ('queued', 'running', 'done', 'failed'))
);

CREATE INDEX idx_shortlist_runs_started ON shortlist_runs (started_at DESC);

-- ---------------------------------------------------------------------
-- 6. shortlist_results : the ranked candidates of each run
-- ---------------------------------------------------------------------
CREATE TABLE shortlist_results (
    run_id                VARCHAR(32)  NOT NULL REFERENCES shortlist_runs(id)  ON DELETE CASCADE,
    rank                  INT          NOT NULL,
    candidate_id          BIGINT       NOT NULL REFERENCES candidates(id)      ON DELETE CASCADE,

    final_score           NUMERIC(5,1) NOT NULL,
    rule_score            NUMERIC(5,1),
    llm_score             NUMERIC(5,1),

    -- Filled in after the four-dimension scoring upgrade
    skills_score          NUMERIC(5,1),
    experience_score      NUMERIC(5,1),
    education_score       NUMERIC(5,1),
    qualifications_score  NUMERIC(5,1),

    details               JSONB        NOT NULL DEFAULT '{}',  -- strengths, gaps, summary, missing skills

    PRIMARY KEY (run_id, rank),
    CONSTRAINT uq_results_run_candidate UNIQUE (run_id, candidate_id)
);

CREATE INDEX idx_shortlist_results_candidate ON shortlist_results (candidate_id);

-- ---------------------------------------------------------------------
-- Permissions for the FastAPI role.
-- credentials_all is deliberately NOT granted: the model server can never read accounts.
-- ---------------------------------------------------------------------
GRANT USAGE ON SCHEMA public TO fastapi_svc;

GRANT SELECT ON candidates, vacancies TO fastapi_svc;

GRANT SELECT, INSERT, UPDATE, DELETE
    ON candidate_profiles, shortlist_runs, shortlist_results
    TO fastapi_svc;

COMMIT;
